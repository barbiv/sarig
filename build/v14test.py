"""1.4 checks: catalog + tab4u search rows, easy/regular version, strumming strips in stage/sheet, settings picker."""
import asyncio
from playwright.async_api import async_playwright
OUT = '/tmp/claude-0/-home-claude/8249339a-1fe3-5830-b016-fd59610196bc/scratchpad/shots/'

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 393, 'height': 852}, device_scale_factor=2, is_mobile=True, has_touch=True, color_scheme='dark')
        pg = await ctx.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'ERR_' not in m.text and '404' not in m.text else None)
        await pg.route('https://lrclib.net/**', lambda r: r.fulfill(status=404, body=''))
        await pg.route('**/search?q=**', lambda r: r.fulfill(status=200, headers={'access-control-allow-origin': '*'}, content_type='application/json', body='{"items":[]}'))
        await pg.goto('http://localhost:8765/', wait_until='networkidle')
        await pg.click('.onb button.btn'); await pg.wait_for_timeout(500)
        await pg.fill('#sg-q', 'טונה'); await pg.wait_for_timeout(600)
        print('catalog', await pg.evaluate("[document.querySelectorAll('#sg-cat [data-ci]').length, !!document.querySelector('[data-t4]')]"))
        await pg.screenshot(path=OUT + 'v1_catalog.png')
        await pg.click('#sg-cat [data-ci] >> nth=0'); await pg.wait_for_timeout(700)
        print('import sheet', await pg.evaluate("[document.querySelector('.sheet h2').textContent, document.querySelector('.sheet a.btn').href]"))
        await pg.screenshot(path=OUT + 'v2_import.png')
        await pg.click('.sheet [data-close]'); await pg.wait_for_timeout(500)
        await pg.fill('#sg-q', 'what a wonderful world'); await pg.wait_for_timeout(600)
        print('waww', await pg.evaluate("[...document.querySelectorAll('.song')].slice(0,3).map(s=>s.querySelector('.t').textContent+' / '+s.querySelector('.ar').textContent)"))
        await pg.click('.song >> nth=0'); await pg.wait_for_timeout(1500)
        print('level', await pg.evaluate("[document.querySelector('#pl-level').hidden, document.querySelector('#pl-strum').dataset.p]"))
        await pg.click('#pl-play'); await pg.wait_for_timeout(9000)
        await pg.screenshot(path=OUT + 'v3_stage_reg.png')
        if not await pg.evaluate("document.querySelector('#pl-level').hidden"):
            await pg.click('#pl-level [data-lv=easy]'); await pg.wait_for_timeout(4000)
            print('easy', await pg.evaluate("[document.querySelector('#pl-set-l').textContent, document.querySelector('#pl-strum').dataset.p, (document.querySelector('.toast.on')||{}).textContent]"))
            await pg.screenshot(path=OUT + 'v4_stage_easy.png')
        await pg.click('#pl-play'); await pg.wait_for_timeout(300)
        await pg.click('#pl-set'); await pg.wait_for_timeout(600)
        await pg.evaluate("document.querySelector('.strumpick').scrollIntoView()"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=OUT + 'v5_settings.png')
        await pg.click('.strumpick [data-strum=eighths]'); await pg.wait_for_timeout(300)
        await pg.click('.sheet [data-close]'); await pg.wait_for_timeout(500)
        print('strum after pick', await pg.evaluate("document.querySelector('#pl-strum').dataset.p"))
        await pg.click('#pl-view'); await pg.wait_for_timeout(600)
        await pg.click('#pl-play'); await pg.wait_for_timeout(6000)
        await pg.screenshot(path=OUT + 'v6_sheet.png')
        await pg.click('#pl-play'); await pg.wait_for_timeout(200)
        await pg.click('#pl-view'); await pg.click('#pl-view'); await pg.click('#pl-view'); await pg.wait_for_timeout(500)
        await pg.click('.screen [data-back]'); await pg.wait_for_timeout(700)
        await pg.fill('#sg-q', 'ירושלים של זהב'); await pg.wait_for_timeout(500)
        await pg.click('.song >> nth=0'); await pg.wait_for_timeout(1200)
        await pg.click('#pl-play'); await pg.wait_for_timeout(5000)
        await pg.screenshot(path=OUT + 'v7_he_bars.png')
        await pg.click('.screen [data-back]'); await pg.wait_for_timeout(700)
        await pg.fill('#sg-q', 'zzqqxx'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT + 'v8_noresults.png')
        print('\n'.join(errs[:20]))
        await b.close()
asyncio.run(main())

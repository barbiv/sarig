import asyncio, sys
from playwright.async_api import async_playwright
OUT = '/tmp/claude-0/-home-claude/8249339a-1fe3-5830-b016-fd59610196bc/scratchpad/shots/'
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True, color_scheme='dark',
                                  user_agent='Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1')
        pg = await ctx.new_page()
        errs = []
        pg.on('console', lambda m: errs.append(f'{m.type}: {m.text}') if m.type in ('error', 'warning') else None)
        pg.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
        await pg.goto('http://localhost:8765/', wait_until='networkidle')
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path=OUT + '01_onb.png')
        await pg.click('.onb button.btn')
        await pg.wait_for_timeout(400)
        await pg.screenshot(path=OUT + '02_songs.png')
        # filters
        await pg.click('#sg-filter'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT + '03_filters.png')
        await pg.click('.sheet [data-close]'); await pg.wait_for_timeout(400)
        await pg.fill('#sg-q', 'let it be'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT + '04_search.png')
        await pg.click('.song >> nth=0'); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=OUT + '05_player.png')
        await pg.click('#pl-play'); await pg.wait_for_timeout(6000)
        await pg.screenshot(path=OUT + '06_playing.png')
        await pg.click('#pl-view'); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=OUT + '07_grid.png')
        await pg.click('#pl-play'); await pg.wait_for_timeout(300)
        await pg.click('.screen [data-back]'); await pg.wait_for_timeout(500)
        await pg.click('.tab[data-tab=chords]'); await pg.wait_for_timeout(600)
        await pg.screenshot(path=OUT + '08_chords.png')
        await pg.click('.ccard >> nth=0'); await pg.wait_for_timeout(600)
        await pg.screenshot(path=OUT + '09_chord.png')
        await pg.click('[data-known]'); await pg.wait_for_timeout(300)
        await pg.click('.sheet [data-close]'); await pg.wait_for_timeout(400)
        await pg.click('.tab[data-tab=trainer]'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT + '10_trainer.png')
        await pg.click('[data-ex] >> nth=0'); await pg.wait_for_timeout(600)
        await pg.click('[data-dur="30"]'); await pg.click('#ex-start'); await pg.wait_for_timeout(2300)
        for i in range(12):
            await pg.tap('[data-tap]'); await pg.wait_for_timeout(120)
        await pg.screenshot(path=OUT + '11_ex_run.png')
        await pg.wait_for_timeout(29000)
        await pg.screenshot(path=OUT + '12_ex_done.png')
        await pg.click('button[data-tab=stats]'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT + '13_ex_stats.png', full_page=False)
        await pg.click('.screen [data-back]'); await pg.wait_for_timeout(500)
        await pg.click('.tab[data-tab=progress]'); await pg.wait_for_timeout(800)
        await pg.screenshot(path=OUT + '14_progress.png')
        await pg.click('.tab[data-tab=favs]'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT + '15_favs.png')
        # reload to check persistence
        await pg.reload(wait_until='networkidle'); await pg.wait_for_timeout(1200)
        st = await pg.evaluate("JSON.parse(localStorage.getItem('fretline-state'))")
        print('persist: practice', len(st['practice']), 'recent', st['recent'][:2], 'known', st['known'], 'plays', len(st['plays']))
        await pg.screenshot(path=OUT + '16_reload.png')
        print('\n'.join(errs[:30]))
        await b.close()
asyncio.run(main())
